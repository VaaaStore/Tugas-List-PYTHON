nilai = [75, 80, 90, 65, 85, 70]

jumlah_mahasiswa = len(nilai)
nilai_min = min(nilai)
nilai_max = max(nilai)
total_nilai = sum(nilai)
rata_rata = total_nilai / jumlah_mahasiswa

print(f"Jumlah Mahasiswa: {jumlah_mahasiswa}")
print(f"Nilai min: {nilai_min}")
print(f"Nilai max: {nilai_max}")
print(f"Total: {total_nilai}")
print(f"Rata-rata: {rata_rata}")